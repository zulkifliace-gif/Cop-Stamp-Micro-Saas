-- Stores policies
create policy "Allow anyone to read store info"
    on public.stores for select
    using (true);

-- CATATAN: sengaja TIADA policy INSERT untuk public.stores.
-- Pendaftaran kedai baharu (onboarding) hanya berlaku melalui
-- POST /api/store/settings, yang guna service-role admin client
-- (bypass RLS) selepas semakan auth + existingStaff di app layer.
-- Jangan tambah "with check (auth.uid() is not null)" — itu benarkan
-- SESIAPA authenticated insert terus ke stores via PostgREST, bypass
-- app sepenuhnya.

create policy "Allow store owners to update store settings"
    on public.stores for update
    using (
        exists (
            select 1 from public.store_staff
            where store_staff.store_id = stores.id
              and store_staff.user_id = auth.uid()
              and store_staff.role = 'owner'
        )
    );

