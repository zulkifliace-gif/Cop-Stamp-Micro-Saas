-- ==============================================================================
-- Auth Trigger: Auto-create customer profile on auth.users creation
-- ==============================================================================

create or replace function public.handle_new_customer()
returns trigger as $$
begin
  insert into public.customer_profiles (id, email, full_name, avatar_url)
  values (
    new.id,
    new.email,
    coalesce(new.raw_user_meta_data->>'full_name', new.raw_user_meta_data->>'name', split_part(new.email, '@', 1)),
    new.raw_user_meta_data->>'avatar_url'
  )
  on conflict (id) do update
  set
    email = coalesce(excluded.email, customer_profiles.email),
    full_name = coalesce(excluded.full_name, customer_profiles.full_name),
    avatar_url = coalesce(excluded.avatar_url, customer_profiles.avatar_url),
    updated_at = now();
  return new;
end;
$$ language plpgsql security definer
set search_path = public, pg_temp;

drop trigger if exists on_auth_user_created on auth.users;
create trigger on_auth_user_created
  after insert on auth.users
  for each row execute function public.handle_new_customer();

-- ==============================================================================
-- RPC Function: claim_stamp_token (Atomic Token Claim)
-- ==============================================================================

create or replace function public.claim_stamp_token(p_token text)
returns jsonb as $$
declare
    v_customer_id uuid;
    v_token_row public.stamp_tokens%ROWTYPE;
    v_store_row public.stores%ROWTYPE;
    v_prev_stamps int := 0;
    v_new_stamps int := 0;
begin
    -- 1. Check authenticated user
    v_customer_id := auth.uid();
    if v_customer_id is null then
        return jsonb_build_object(
            'success', false,
            'error', 'unauthenticated',
            'message', 'Sila log masuk untuk menebus cop stamp.'
        );
    end if;

    -- 2. Lock & fetch token
    select * into v_token_row
    from public.stamp_tokens
    where token = p_token
    for update;

    if not found then
        return jsonb_build_object(
            'success', false,
            'error', 'not_found',
            'message', 'Pautan cop ini tidak sah atau tidak wujud.'
        );
    end if;

    -- 3. Validate token status
    if v_token_row.status = 'claimed' then
        return jsonb_build_object(
            'success', false,
            'error', 'already_claimed',
            'message', 'Cop ini sudah diambil sebelum ini.'
        );
    end if;

    if v_token_row.expires_at < now() or v_token_row.status = 'expired' then
        update public.stamp_tokens
        set status = 'expired'
        where id = v_token_row.id;

        return jsonb_build_object(
            'success', false,
            'error', 'expired',
            'message', 'Pautan ini telah luput tempoh (sah 15 minit sahaja).'
        );
    end if;

    -- 4. Get store information
    select * into v_store_row
    from public.stores
    where id = v_token_row.store_id;

    -- 5. Get current loyalty balance
    select coalesce(total_stamps, 0) into v_prev_stamps
    from public.customer_loyalty
    where customer_id = v_customer_id
      and store_id = v_token_row.store_id;

    if v_prev_stamps is null then
        v_prev_stamps := 0;
    end if;

    v_new_stamps := v_prev_stamps + v_token_row.stamp_count;

    -- 6. Upsert customer loyalty balance
    insert into public.customer_loyalty (customer_id, store_id, total_stamps, updated_at)
    values (v_customer_id, v_token_row.store_id, v_new_stamps, now())
    on conflict (customer_id, store_id)
    do update set
        total_stamps = public.customer_loyalty.total_stamps + v_token_row.stamp_count,
        updated_at = now();

    -- 7. Mark token as claimed
    update public.stamp_tokens
    set
        status = 'claimed',
        claimed_by = v_customer_id,
        claimed_at = now()
    where id = v_token_row.id;

    -- 8. Return comprehensive payload for frontend animations
    return jsonb_build_object(
        'success', true,
        'storeId', v_token_row.store_id,
        'stampsAdded', v_token_row.stamp_count,
        'previousStamps', v_prev_stamps,
        'newTotal', v_new_stamps,
        'storeName', coalesce(v_store_row.name, 'Kedai'),
        'stampsRequired', coalesce(v_store_row.stamps_required, 10),
        'rewardDescription', coalesce(v_store_row.reward_description, '1 ganjaran istimewa')
    );
end;
$$ language plpgsql security definer
set search_path = public, pg_temp;

-- ==============================================================================
-- Rate Limiting: persistent table + atomic RPC (ganti in-memory Map di
-- lib/rate-limit.ts, yang tak reliable merentasi instance serverless)
-- ==============================================================================

create table if not exists public.api_rate_limits (
    identifier text primary key,
    count int not null default 1,
    reset_time timestamptz not null
);

-- Table ni hanya diakses melalui service-role client (admin) dari server,
-- jadi tak perlu RLS/anon access. Enable RLS tanpa policy = deny-by-default
-- untuk anon/authenticated; service role sentiasa bypass RLS.
alter table public.api_rate_limits enable row level security;

create or replace function public.check_rate_limit(
    p_identifier text,
    p_max_requests int,
    p_window_seconds int
)
returns jsonb as $$
declare
    v_now timestamptz := now();
    v_record public.api_rate_limits%ROWTYPE;
begin
    select * into v_record
    from public.api_rate_limits
    where identifier = p_identifier
    for update;

    -- Tiada rekod, atau window sebelumnya dah tamat -> mula window baru
    if not found or v_record.reset_time < v_now then
        insert into public.api_rate_limits (identifier, count, reset_time)
        values (p_identifier, 1, v_now + make_interval(secs => p_window_seconds))
        on conflict (identifier) do update
        set count = 1,
            reset_time = excluded.reset_time
        returning * into v_record;

        return jsonb_build_object(
            'success', true,
            'remaining', p_max_requests - 1,
            'reset', floor(extract(epoch from v_record.reset_time) * 1000)
        );
    end if;

    if v_record.count >= p_max_requests then
        return jsonb_build_object(
            'success', false,
            'remaining', 0,
            'reset', floor(extract(epoch from v_record.reset_time) * 1000)
        );
    end if;

    update public.api_rate_limits
    set count = count + 1
    where identifier = p_identifier
    returning * into v_record;

    return jsonb_build_object(
        'success', true,
        'remaining', p_max_requests - v_record.count,
        'reset', floor(extract(epoch from v_record.reset_time) * 1000)
    );
end;
$$ language plpgsql security definer
set search_path = public, pg_temp;

-- ==============================================================================
-- RPC Function: redeem_reward_atomic (Cashier Redeems Customer Stamp Reward)
-- ==============================================================================

create or replace function public.redeem_reward_atomic(
    p_customer_id uuid,
    p_store_id uuid,
    p_reward_count int default 1
)
returns jsonb as $$
declare
    v_staff_id uuid;
    v_store public.stores%ROWTYPE;
    v_loyalty public.customer_loyalty%ROWTYPE;
    v_customer_profile public.customer_profiles%ROWTYPE;
    v_stamps_needed int;
    v_new_stamps int;
begin
    v_staff_id := auth.uid();
    if v_staff_id is null then
        return jsonb_build_object('success', false, 'error', 'unauthenticated', 'message', 'Sila log masuk.');
    end if;

    -- Verify cashier has access to store
    if not exists (
        select 1 from public.store_staff
        where store_id = p_store_id and user_id = v_staff_id
    ) then
        return jsonb_build_object('success', false, 'error', 'forbidden', 'message', 'Tiada kebenaran untuk kedai ini.');
    end if;

    -- Get store details
    select * into v_store from public.stores where id = p_store_id;
    if not found then
        return jsonb_build_object('success', false, 'error', 'store_not_found', 'message', 'Kedai tidak dijumpai.');
    end if;

    -- Lock customer loyalty record
    select * into v_loyalty
    from public.customer_loyalty
    where customer_id = p_customer_id and store_id = p_store_id
    for update;

    if not found then
        return jsonb_build_object('success', false, 'error', 'no_stamps', 'message', 'Pelanggan belum mempunyai rekod cop di kedai ini.');
    end if;

    v_stamps_needed := v_store.stamps_required * coalesce(p_reward_count, 1);

    if v_loyalty.total_stamps < v_stamps_needed then
        return jsonb_build_object(
            'success', false,
            'error', 'insufficient_stamps',
            'message', format('Cop tidak mencukupi (%s/%s diperlukan).', v_loyalty.total_stamps, v_stamps_needed),
            'totalStamps', v_loyalty.total_stamps,
            'stampsRequired', v_store.stamps_required
        );
    end if;

    -- Deduct stamps
    v_new_stamps := v_loyalty.total_stamps - v_stamps_needed;
    update public.customer_loyalty
    set total_stamps = v_new_stamps, updated_at = now()
    where customer_id = p_customer_id and store_id = p_store_id;

    -- Fetch customer profile
    select * into v_customer_profile from public.customer_profiles where id = p_customer_id;

    -- Insert redemption record
    insert into public.stamp_redemptions (
        customer_id,
        customer_email,
        store_id,
        stamps_used,
        reward_details,
        redeemed_by,
        created_at
    )
    values (
        p_customer_id,
        v_customer_profile.email,
        p_store_id,
        v_stamps_needed,
        v_store.reward_description,
        v_staff_id,
        now()
    );

    return jsonb_build_object(
        'success', true,
        'message', 'Ganjaran berjaya ditebus!',
        'previousStamps', v_loyalty.total_stamps,
        'stampsUsed', v_stamps_needed,
        'remainingStamps', v_new_stamps,
        'rewardDescription', v_store.reward_description,
        'customerEmail', v_customer_profile.email
    );
end;
$$ language plpgsql security definer
set search_path = public, pg_temp;
