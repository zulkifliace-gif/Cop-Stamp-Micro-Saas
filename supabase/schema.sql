-- ==============================================================================
-- Schema: Micro SaaS Cop Stamp (Digital Loyalty Stamp System)
-- ==============================================================================

-- 1. Enable UUID Extension
create extension if not exists "uuid-ossp";

-- 2. Stores Table
create table if not exists public.stores (
    id uuid primary key default gen_random_uuid(),
    name text not null,
    stamps_required int not null default 10 check (stamps_required > 0),
    reward_description text not null default '1 minuman panas percuma (saiz regular)',
    logo_url text,
    reward_image_url text,
    rewards jsonb default '[]'::jsonb,
    created_at timestamptz not null default now(),
    updated_at timestamptz not null default now()
);

-- Backward compatibility columns
alter table public.stores add column if not exists logo_url text;
alter table public.stores add column if not exists reward_image_url text;
alter table public.stores add column if not exists rewards jsonb default '[]'::jsonb;

-- Subscription & Stripe columns
alter table public.stores add column if not exists plan_type text default 'free';
alter table public.stores add column if not exists subscription_status text default 'active';
alter table public.stores add column if not exists stripe_customer_id text;
alter table public.stores add column if not exists stripe_subscription_id text;
alter table public.stores add column if not exists subscription_end_date timestamptz;


-- 3. Store Staff Table (cashiers and owners)
create table if not exists public.store_staff (
    id uuid primary key default gen_random_uuid(),
    store_id uuid not null references public.stores(id) on delete cascade,
    user_id uuid not null references auth.users(id) on delete cascade,
    role text not null default 'cashier' check (role in ('owner', 'cashier')),
    created_at timestamptz not null default now(),
    unique(store_id, user_id)
);

-- 4. Customer Profiles Table
create table if not exists public.customer_profiles (
    id uuid primary key references auth.users(id) on delete cascade,
    email text,
    full_name text,
    avatar_url text,
    created_at timestamptz not null default now(),
    updated_at timestamptz not null default now()
);

create index if not exists idx_customer_profiles_email on public.customer_profiles(email);

-- 5. Stamp Tokens Table (one-time use claim tokens generated by cashiers)
create table if not exists public.stamp_tokens (
    id uuid primary key default gen_random_uuid(),
    token text unique not null,
    store_id uuid not null references public.stores(id) on delete cascade,
    stamp_count int not null default 1 check (stamp_count > 0),
    status text not null default 'pending' check (status in ('pending', 'claimed', 'expired')),
    delivery_method text not null default 'qr' check (delivery_method in ('qr', 'email')),
    recipient_email text,
    created_by uuid references auth.users(id),
    claimed_by uuid references auth.users(id),
    claimed_at timestamptz,
    expires_at timestamptz not null default (now() + interval '30 minutes'),
    created_at timestamptz not null default now()
);

create index if not exists idx_stamp_tokens_token on public.stamp_tokens(token);
create index if not exists idx_stamp_tokens_store_id on public.stamp_tokens(store_id);
create index if not exists idx_stamp_tokens_status on public.stamp_tokens(status);

-- 6. Customer Loyalty Table (tracks total stamp points per customer per store)
create table if not exists public.customer_loyalty (
    id uuid primary key default gen_random_uuid(),
    customer_id uuid not null references auth.users(id) on delete cascade,
    store_id uuid not null references public.stores(id) on delete cascade,
    total_stamps int not null default 0 check (total_stamps >= 0),
    created_at timestamptz not null default now(),
    updated_at timestamptz not null default now(),
    unique(customer_id, store_id)
);

create index if not exists idx_customer_loyalty_lookup on public.customer_loyalty(customer_id, store_id);

-- 7. Stamp Redemptions Table (records when customer claims rewards)
create table if not exists public.stamp_redemptions (
    id uuid primary key default gen_random_uuid(),
    customer_id uuid not null references auth.users(id) on delete cascade,
    customer_email text,
    store_id uuid not null references public.stores(id) on delete cascade,
    stamps_used int not null check (stamps_used > 0),
    reward_details text,
    redeemed_by uuid references auth.users(id),
    created_at timestamptz not null default now()
);

create index if not exists idx_stamp_redemptions_store on public.stamp_redemptions(store_id, created_at desc);

